#!/usr/bin/env python3
"""C for the host build from the matching build's gap objects (bytes no source file owns yet, see docs/unmatched.md).

One C file for every host architecture (modern/gen/gaps.c): each label of a gap object's data/rodata section that the
game uses becomes a C object of its own, from the label to the next label (or the section's end):
- the bytes as they are (`const unsigned char x[n]`, 4-byte aligned), when no word in it has a relocation;
- a table of pointers (`void *x[n] = {&sym + addend, ...}`), when every word has one (R_ARM_ABS32), so that the
  pointers are the host's, 8 bytes each on 64-bit hosts.
A label with a mix of the two stops the script (write its type in C). Functions can't be reused on the host: they
are listed in a comment, to be written in C (modern/host/gaps_code.c).

Labels defined in the game's sources instead (every bss label: the zero-initialised variables, with their real
types; SOURCE_DEFINED: data whose layout depends on the host - member-function pointers, a vtable) and labels nothing
uses (UNUSED: checked with `nm -u` of the game object of both builds) are left out.

Usage: host_gaps.py <objects_aliases.txt> <out.c>
"""
import struct
import sys

from elftools.elf.elffile import ELFFile
from elftools.elf.relocation import RelocationSection

# Defined in the sources (2026-10-08): ProcBase's data (src/autoload_2/unk_020ec848.cpp: the next id; the phase
# member-function pointers and the class's vtable are the compiler's now), the phase member-function pointers of
# src/itcm/unk_01ffd0e4.cpp. Every bss label too (zero-initialised variables: defined with their types in a unit that
# uses them, or src/autoload_2/gap_vars.c), without a list.
SOURCE_DEFINED = {
    "sProcNextId", "data_0213b124", "data_0213b12c", "data_0213b134", "data_0213b13c", "data_0213b144",
    "data_0213b14c", "data_0213b15c",
    "data_01ffd0b4", "data_01ffd0bc", "data_01ffd0c4", "data_01ffd0cc", "data_01ffd0d4", "data_01ffd0dc",
}
# Not referenced by the game: BuildInfo (the SDK's build strings, with DS addresses in them), data_02000b84 (the SDK
# version strings), data_020e1178 (the effect process's profile: src/main/unk_020e1e2c.cpp defines its own),
# .p__sinit_020c5fa0 (a static initialiser's .ctor entry: the host's .init_array has it).
UNUSED = {"BuildInfo", "data_02000b84", "data_020e1178", ".p__sinit_020c5fa0"}
# Functions in gap code that the sources define now
DECOMPILED = {"Snd_CalcListenerDistance"}


def main():
    aliases, out_path = sys.argv[1], sys.argv[2]
    gaps = [l.strip().strip('"') for l in open(aliases) if "/delinks/_dsd_gap@" in l]
    out = ["// generated by tools/host_gaps.py (the DS's data between the decomp's units)", ""]
    externs, objs, code_syms = set(), [], []
    for path in gaps:
        with open(path, "rb") as f:
            elf = ELFFile(f)
            symtab = elf.get_section_by_name(".symtab")
            for si, sec in enumerate(elf.iter_sections()):
                if sec["sh_type"] not in ("SHT_PROGBITS", "SHT_NOBITS") or not sec["sh_flags"] & 2 or sec["sh_size"] == 0:
                    continue
                syms = [s for s in symtab.iter_symbols() if s["st_shndx"] == si and s.name and
                        s["st_info"]["type"] in ("STT_OBJECT", "STT_FUNC", "STT_NOTYPE") and not s.name.startswith(("$", ".L"))]
                if sec["sh_flags"] & 4:  # executable: functions need C; data labels inside are kept
                    code_syms += [f"{s.name} ({path.split('@')[-1]})" for s in syms
                                  if s["st_info"]["type"] == "STT_FUNC" and s.name not in DECOMPILED]
                    syms = [s for s in syms if s["st_info"]["type"] != "STT_FUNC"]
                if sec["sh_type"] == "SHT_NOBITS":
                    continue  # zero-initialised: defined in the sources with their types
                data = sec.data()
                relocs = {}
                for rs in elf.iter_sections():
                    if not isinstance(rs, RelocationSection) or rs["sh_info"] != si:
                        continue
                    for r in rs.iter_relocations():
                        sym = symtab.get_symbol(r["r_info_sym"])
                        if r["r_info_type"] != 2 or sym["st_info"]["type"] == "STT_SECTION" or not sym.name:
                            continue
                        add = r["r_addend"] if r.is_RELA() else struct.unpack_from("<I", data, r["r_offset"])[0]
                        relocs[r["r_offset"]] = (sym.name, add)
                starts = sorted({s["st_value"] for s in syms})
                for s in sorted(syms, key=lambda s: s["st_value"]):
                    if s.name in SOURCE_DEFINED or s.name in UNUSED:
                        continue
                    lo = s["st_value"]
                    hi = min([v for v in starts if v > lo] + [sec["sh_size"]])
                    ro = "const " if not sec["sh_flags"] & 1 else ""
                    inside = [o for o in relocs if lo <= o < hi]
                    if not inside:
                        body = ", ".join(f"{b:#04x}" for b in data[lo:hi])
                        objs.append(f"_Alignas(4) {ro}unsigned char {s.name}[{hi - lo}] = {{ {body} }};")
                    elif lo % 4 == 0 and hi % 4 == 0 and len(inside) == (hi - lo) // 4:
                        ptrs = []
                        for o in range(lo, hi, 4):
                            name, add = relocs[o]
                            externs.add(name)
                            ptrs.append(f"(char *)&{name} + {add:#x}" if add else f"&{name}")
                        objs.append(f"void *{ro}{s.name}[{(hi - lo) // 4}] = {{ {', '.join(ptrs)} }};")
                    else:
                        sys.exit(f"host_gaps.py: {s.name}: pointers and data mixed (write its type in C)")
    out += [f"extern char {n};" for n in sorted(externs)] + [""] + objs + [""]
    out.append("// code in gaps (written in C in modern/host/gaps_code.c): " + ", ".join(code_syms))
    open(out_path, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
