#!/usr/bin/env python3
"""A text file as a C string constant: host_embed.py <in> <out.h> <name> (modern/host/gpu2d.wgsl for
wgpu_display.c)."""
import sys

src, out, name = sys.argv[1:4]
lines = open(src, encoding="utf-8").read().splitlines()
with open(out, "w", encoding="utf-8") as f:
    f.write(f"// generated by tools/host_embed.py from {src}\nstatic const char {name}[] =\n")
    for line in lines:
        f.write('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"\n')
    f.write(";\n")
