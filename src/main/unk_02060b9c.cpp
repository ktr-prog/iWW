extern "C" s32 Insect_HourToTimeSlot(u32 x) {
    if (x >= 4 && x <= 7) return 1;
    if (x >= 8 && x <= 0xf) return 2;
    if (x == 0x10) return 3;
    if ((u8)(x + 0xef) <= 1) return 4;
    if (x >= 0x13 && x <= 0x16) return 5;
    return 0;
}

