extern "C" void Weather_InitNew(WeatherRecord *self) {
    sWeatherPrevDayRain = 0;
    self->rained = 0;
    self->day = 1;
    self->month = 1;
    self->year = 0;
    self->unk_03 = 0;
    self->day = 0;
    Weather_Apply(self);
}

