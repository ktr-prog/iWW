extern "C" s32 StarSky_FindConstellationByLine(u16 v)
{
    s32 i, j;
    for (i = 0; i < 16; i++) {
        ConstellationRecord *q = Constellation_GetRecord(i);
        if (q == 0) {
            continue;
        }
        for (j = 0; j < 16; j++) {
            if (v == q->lines[j]) {
                return i;
            }
        }
    }
    return -1;
}

extern "C" void StarSky_CollectStars(ConstellationRecord *p, u8 *out)
{
    s32 i, k, j, n;
    const u8 *q;
    for (i = 0; i < 0x11; i++) {
        out[i] = 0xff;
    }
    n = 0;
    for (i = 0; i < 16; i++) {
        u32 v = p->lines[i];
        if (v == 0xffff) {
            continue;
        }
        q = StarSky_GetLineStars(v);
        for (k = 0; k < 2; k++) {
            const u8 *pk;
            for (j = 0, pk = q + k; n >= j; j++) {
                if (j == n) {
                    out[n] = *pk;
                    n++;
                    j = n + 1;
                } else if (out[j] == q[k]) {
                    j = n + 1;
                }
            }
        }
    }
}

