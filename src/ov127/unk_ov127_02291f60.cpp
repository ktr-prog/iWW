extern "C" void StarSky_Update(StarSkyView *s)
{
    if (StarSky_HasFlags(s, 4)) {
        StarSky_StepToTarget(s);
    }
    if (StarSky_HasFlags(s, 1)) {
        s32 v;
        Gfx2d_SetLayerOffset(s->skyLayer, s->scrollX, s->scrollY);
        StarSky_ClearFlags(s, 1);
        v = 0;
        s32 t = s->scrollY;
        if (t < 0) {
            v = ((t - 7) << 13) >> 16;
        } else if (t >= 0x40) {
            v = ((t - 0x39) << 13) >> 16;
        }
        if (v != s->clipRows) {
            s->clipRows = v;
            StarSky_SetFlags(s, 2);
        }
    }
    if (StarSky_HasFlags(s, 2)) {
        s32 cnt;
        u16 *p1;
        u16 *p2;
        s32 j;
        s32 i;
        MI_CpuCopy8(s->skyScreen, s->skyScreenWork, 0x1000);
        cnt = s->clipRows;
        if (cnt > 0) {
            p1 = s->skyScreenWork;
            p2 = p1 + 0x400;
            for (i = 0; i < s->clipRows; i++) {
                for (j = 0; j < 0x20; j++) {
                    *p1 = 0x4010;
                    *p2 = 0x4010;
                    p1++;
                    p2++;
                }
            }
        } else if (cnt < 0) {
            p1 = s->skyScreenWork + ((cnt + 0x20) << 5);
            p2 = p1 + 0x400;
            for (i = 0; i > s->clipRows; i--) {
                for (j = 0; j < 0x20; j++) {
                    *p1 = 0x4010;
                    *p2 = 0x4010;
                    p1++;
                    p2++;
                }
            }
        }
        s->screenTask.requestScreen(s->skyScreenWork, s->skyLayer, 0x1000, 0);
        StarSky_ClearFlags(s, 2);
    }
}

